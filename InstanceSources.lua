-- Xal's Warchest - which dungeon/raid and boss drops each weapon
-- appearance, across every expansion in the game's history.
--
-- C_TransmogCollection.GetAppearanceSourceDrops already answers this from
-- the Encounter Journal for most items; this table fills the gaps where
-- that API comes back empty (very new content, or older instances the
-- Journal tracks sparsely).
--
-- Merged from multiple research passes - see
-- D:\WoW_Addons\Dev\warchest_research\instance_drops*.lua and the
-- gap2_<xpac>_drops.lua gap-closure files for the original per-pass
-- research and ID policy write-ups. Indices renumbered during merges.
--
-- IMPORTANT: this file is dungeon/raid drops ONLY. Gap-closure passes
-- repeatedly found open-world zone drops mixed in (Wowhead's item pages
-- show a plain creature "dropped-by" the same way for an open-world rare
-- as for a dungeon boss, with nothing in the page data distinguishing the
-- two) - every merge into this file filters against the already-known
-- instance list and routes anything unmatched to
-- gap2_world_drop_candidates.json for a future WorldDropSources.lua
-- instead of polluting this file with fake instances.
--
-- 3975 unique itemIDs across 181 dungeons/raids,
-- 1333 unique (instance, boss) pairs.
--
-- Three-level share, same technique Armoire's own InstanceDropSources.lua
-- uses: InstanceList[i]={name,kind}, InstanceBossPairs[p]={instanceIndex,
-- boss}, InstanceDropSources[itemID]=pairIndex.

